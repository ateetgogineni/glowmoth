using System.IO;
using UnityEngine;

namespace Glowmoth
{
    /// <summary>
    /// Development tool for recording gameplay videos. Inert unless the player is launched with
    ///   -glowmothCapture "C:\path\to\frames" [-captureLevels 1,4,8]
    /// It locks the frame rate to 30 fps (Time.captureFramerate), plays each listed level by tapping the
    /// lamp at scripted times, writes every frame as a PNG, and quits. Encode with ffmpeg afterwards.
    /// Tap schedules come from the off-line solver, so timing is deterministic.
    /// </summary>
    public sealed class AutoPlayCapture : MonoBehaviour
    {
        struct Tap { public int Frame; public Vector2 Pos; public Tap(int f, float x, float y) { Frame = f; Pos = new Vector2(x, y); } }

        // Level index -> taps (frame number since level start at 30 fps, world position).
        static Tap[] Script(int level)
        {
            switch (level)
            {
                // Generated by the off-line solver (3 stars each); frames must stay in sync with level time.
                case 0: return new[] { new Tap(1, 0f, 4.5f) };
                case 3: return new[] { new Tap(1, 3.6f, -5f), new Tap(47, 3.3f, 1f), new Tap(89, 1.5f, 6f), new Tap(126, -3f, 4.5f) };
                case 7: return new[] { new Tap(1, -3.5f, 3f), new Tap(64, 0f, 5f) };
                case 12: return new[] { new Tap(1, 3.6f, -2f), new Tap(37, -3.6f, 3f), new Tap(96, 0f, 5.2f) };
                case 13: return new[] { new Tap(1, 0f, -2.5f), new Tap(24, 3.2f, 1.4f), new Tap(139, 0f, 5f) };
                case 15: return new[] { new Tap(1, -3f, -3f), new Tap(31, -3.5f, 4.5f), new Tap(72, 0f, 5f) };
                case 19: return new[] { new Tap(1, 3.6f, -5.5f), new Tap(47, 3f, -1.4f), new Tap(78, 1f, 2f), new Tap(111, -3.6f, 5.2f), new Tap(216, 0f, 6f) };
                default: return new Tap[0];
            }
        }

        string outDir;
        int[] levels;
        int levelCursor = -1, frameInLevel, tapCursor, globalFrame, resultFrames;
        Tap[] taps;
        LevelController level;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        static void MaybeStart()
        {
            string[] args = System.Environment.GetCommandLineArgs();
            string dir = null, list = "1,4,8,13,14,16,20";
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (args[i] == "-glowmothCapture") dir = args[i + 1];
                if (args[i] == "-captureLevels") list = args[i + 1];
            }
            if (string.IsNullOrEmpty(dir)) return;

            var go = new GameObject("AutoPlayCapture");
            DontDestroyOnLoad(go);
            var cap = go.AddComponent<AutoPlayCapture>();
            cap.outDir = dir;
            string[] parts = list.Split(',');
            cap.levels = new int[parts.Length];
            for (int i = 0; i < parts.Length; i++) cap.levels[i] = int.Parse(parts[i].Trim()) - 1;
            Directory.CreateDirectory(dir);
            Time.captureFramerate = 30;
        }

        void Start()
        {
            level = FindAnyObjectByType<LevelController>();
            NextLevel();
        }

        void NextLevel()
        {
            levelCursor++;
            if (levelCursor >= levels.Length)
            {
                Debug.Log("[Capture] done, frames: " + globalFrame);
                Application.Quit();
                return;
            }
            int index = levels[levelCursor];
            taps = Script(index);
            tapCursor = 0;
            frameInLevel = 0;
            resultFrames = -1;
            GameRoot.Instance.PlayLevelForCapture(index);
        }

        void Update()
        {
            if (levels == null || levelCursor >= levels.Length || level == null) return;

            while (tapCursor < taps.Length && frameInLevel >= taps[tapCursor].Frame)
            {
                level.PlaceLampAt(taps[tapCursor].Pos);
                tapCursor++;
            }

            // After the result screen has been visible for 2.5 s, move on.
            if (GameRoot.Instance.Current == GameRoot.State.Result)
            {
                if (resultFrames < 0) resultFrames = 0;
                if (++resultFrames > 75) { NextLevel(); return; }
            }
            else if (frameInLevel > 30 * 30)
            {
                Debug.LogWarning("[Capture] level " + (levels[levelCursor] + 1) + " timed out");
                NextLevel();
                return;
            }

            ScreenCapture.CaptureScreenshot(Path.Combine(outDir, "frame_" + globalFrame.ToString("00000") + ".png"));
            globalFrame++;
            frameInLevel++;
        }
    }
}
